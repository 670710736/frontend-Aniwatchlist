-- AniWatchlist application data (PostgreSQL / Supabase).
-- Anime metadata stays in AniList; anime_id stores its external media ID.

CREATE TABLE IF NOT EXISTS members (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           TEXT NOT NULL,
    password_hash   TEXT NOT NULL,
    display_name    TEXT NOT NULL,
    role            TEXT NOT NULL DEFAULT 'member'
                    CHECK (role IN ('member', 'admin')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT members_email_nonempty CHECK (length(trim(email)) > 0),
    CONSTRAINT members_display_name_nonempty CHECK (length(trim(display_name)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS members_email_lower_unique
    ON members (lower(email));

CREATE TABLE IF NOT EXISTS watchlist (
    member_id       BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    anime_id        BIGINT NOT NULL CHECK (anime_id > 0),
    status          TEXT NOT NULL DEFAULT 'planned'
                    CHECK (status IN ('planned', 'watching', 'completed', 'paused', 'dropped')),
    progress        INTEGER NOT NULL DEFAULT 0 CHECK (progress >= 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (member_id, anime_id)
);

CREATE INDEX IF NOT EXISTS watchlist_anime_id_idx ON watchlist (anime_id);

CREATE TABLE IF NOT EXISTS favorites (
    member_id       BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    anime_id        BIGINT NOT NULL CHECK (anime_id > 0),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (member_id, anime_id)
);

CREATE INDEX IF NOT EXISTS favorites_anime_id_idx ON favorites (anime_id);

CREATE TABLE IF NOT EXISTS reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       BIGINT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    anime_id        BIGINT NOT NULL CHECK (anime_id > 0),
    rating          SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 10),
    body            TEXT NOT NULL CHECK (length(trim(body)) BETWEEN 1 AND 2000),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS reviews_anime_created_idx
    ON reviews (anime_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS reviews_member_anime_idx
    ON reviews (member_id, anime_id);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS members_set_updated_at ON members;
CREATE TRIGGER members_set_updated_at
    BEFORE UPDATE ON members
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS watchlist_set_updated_at ON watchlist;
CREATE TRIGGER watchlist_set_updated_at
    BEFORE UPDATE ON watchlist
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS reviews_set_updated_at ON reviews;
CREATE TRIGGER reviews_set_updated_at
    BEFORE UPDATE ON reviews
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
